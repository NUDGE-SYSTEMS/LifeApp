#!/usr/bin/env node
// Build the native app and install it on a device/emulator.
//
//   node scripts/run.mjs android              debug build, Metro on the LAN IP
//   node scripts/run.mjs android --release     standalone build, no Metro needed
//   node scripts/run.mjs ios                   macOS only
//   node scripts/run.mjs ios --release         macOS only
//
// Optional .env keys:
//   ANDROID_DEVICE=<adb serial>   pick a specific Android device
//   DEVICE_UDID=<ios udid>        pick a specific iOS device
//
// Replaces the macOS-only run.sh / release.sh.
import fs from 'node:fs';
import path from 'node:path';
import { lanIp } from './lan-ip.mjs';
import { loadEnvFile, ROOT } from './env.mjs';
import { spawnExpo, runExpo } from './expo.mjs';

loadEnvFile();

const argv = process.argv.slice(2);
const platform = argv.find(a => a === 'android' || a === 'ios');
const release = argv.includes('--release');
const passthrough = argv.filter(a => a !== platform && a !== '--release');

if (!platform) {
  console.error('\nUsage: node scripts/run.mjs <android|ios> [--release]\n');
  process.exit(1);
}

if (platform === 'ios' && process.platform !== 'darwin') {
  console.error(`
ERROR: iOS builds require macOS + Xcode. You're on ${process.platform}.

  Build iOS from Windows with EAS instead:
    npx eas build --platform ios --profile preview

  Or build both platforms at once:
    npm run build:preview
`);
  process.exit(1);
}

// The native project is generated by prebuild and gitignored — regenerate on demand.
const nativeDir = path.join(ROOT, platform);
if (!fs.existsSync(nativeDir)) {
  console.log(`\n  ${platform}/ not found — running prebuild first...\n`);
  const code = await runExpo(['prebuild', '--platform', platform]);
  if (code !== 0) process.exit(code);
}

const args = [`run:${platform}`];
if (release) args.push('--configuration', 'Release');

const device = platform === 'android' ? process.env.ANDROID_DEVICE : process.env.DEVICE_UDID;
if (device) args.push('--device', device);
args.push(...passthrough);

const env = { ...process.env };
if (!release) {
  // Debug builds talk to Metro over the network; hardcode the LAN IP into the bundle
  // URL so the device doesn't try to reach localhost.
  const ip = lanIp();
  if (ip) {
    env.REACT_NATIVE_PACKAGER_HOSTNAME = ip;
    console.log(`\n  Metro host : ${ip}`);
  } else {
    console.warn('\n  WARNING: no LAN IP detected — a physical device may not reach Metro.');
  }
}

console.log(`  Platform   : ${platform}`);
console.log(`  Config     : ${release ? 'Release (standalone)' : 'Debug (needs Metro)'}`);
console.log(`  Device     : ${device || 'auto'}\n`);

const child = spawnExpo(args, { env });
child.on('exit', code => process.exit(code ?? 0));
